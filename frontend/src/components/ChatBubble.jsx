import SectionCard from './SectionCard'

// Minimal, safe formatter: **bold**, "- " bullets and clickable [BNS 123] tags. No raw HTML is injected.
function renderInline(text, onOpen) {
  return text.split(/(\*\*[^*]+\*\*|\[BNS\s*\d+[A-Za-z]?\])/g).map((part, i) => {
    if (/^\*\*[^*]+\*\*$/.test(part)) return <strong key={i}>{part.slice(2, -2)}</strong>
    const m = part.match(/^\[BNS\s*(\d+[A-Za-z]?)\]$/)
    if (m)
      return (
        <button key={i} onClick={() => onOpen(m[1])} className="badge mx-0.5 align-baseline hover:bg-amber-100">
          BNS {m[1]}
        </button>
      )
    return part
  })
}

function renderBody(text, onOpen) {
  return text.split('\n').map((line, i) => {
    if (!line.trim()) return <div key={i} className="h-2" />
    const bullet = line.match(/^\s*[-*]\s+(.*)/)
    if (bullet)
      return (
        <div key={i} className="flex gap-2 pl-1">
          <span className="text-gold-500">•</span>
          <span>{renderInline(bullet[1], onOpen)}</span>
        </div>
      )
    return <p key={i}>{renderInline(line, onOpen)}</p>
  })
}

export default function ChatBubble({ message, onOpenCitation }) {
  const isUser = message.sender === 'user'
  return (
    <div className={`flex ${isUser ? 'justify-end' : 'justify-start'}`}>
      <div className={`max-w-[85%] ${isUser ? '' : 'w-full'}`}>
        <div
          className={`rounded-2xl px-4 py-3 text-sm leading-relaxed ${
            isUser ? 'rounded-br-sm bg-navy-900 text-white' : 'card rounded-bl-sm text-slate-800'
          }`}
        >
          {isUser ? message.text_content : <div className="space-y-1">{renderBody(message.text_content, onOpenCitation)}</div>}
        </div>
        {!isUser && message.provider && (
          <p className="mt-1 text-[11px] text-slate-400">
            {message.provider === 'retrieval-only'
              ? 'AI unavailable: showing retrieved sections only'
              : `Generated by ${message.provider}`}
            {` · ${message.citations?.length || 0} sections retrieved`}
          </p>
        )}
        {!isUser && message.citations?.length > 0 && (
          <div className="mt-3">
            <p className="mb-2 text-xs font-semibold uppercase tracking-wider text-slate-500">Cited BNS Sections</p>
            <div className="grid gap-2 sm:grid-cols-2">
              {message.citations.map((c) => (
                <SectionCard key={c.section_number} section={c} onOpen={onOpenCitation} />
              ))}
            </div>
          </div>
        )}
      </div>
    </div>
  )
}
